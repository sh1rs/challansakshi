// Keep the public worker independent of Vite's page-only development helpers.
import { readFile, writeFile } from 'node:fs/promises';
import ts from 'typescript';
export async function compileVoiceWorker() {
  const source = await readFile(new URL('../lib/workers/voice-recognition.worker.ts', import.meta.url), 'utf8');
  return '// Generated by scripts/build-voice-worker.mjs. Edit the TypeScript source.\n' + ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
}
if (process.argv[1]?.endsWith('build-voice-worker.mjs')) {
  await writeFile(new URL('../public/voice/voice-recognition.worker.js', import.meta.url), await compileVoiceWorker());
}
